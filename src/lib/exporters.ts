function jsonSchemaType(col: Column): Record<string, unknown> {
  const dt = col.dataType;
  let base: Record<string, unknown>;
  if (dt === 'uuid') base = { type: 'string', format: 'uuid' };
  else if (dt === 'string' || dt === 'varchar' || dt === 'text' || dt === 'char') base = { type: 'string' };
  else if (dt === 'integer' || dt === 'bigint' || dt === 'smallint') base = { type: 'integer' };
  else if (dt === 'float' || dt === 'decimal' || dt === 'numeric' || dt === 'number') base = { type: 'number' };
  else if (dt === 'boolean') base = { type: 'boolean' };
  else if (dt === 'date') base = { type: 'string', format: 'date' };
  else if (dt === 'datetime' || dt === 'timestamp' || dt === 'timestamptz') base = { type: 'string', format: 'date-time' };
  else if (dt === 'time') base = { type: 'string', format: 'time' };
  else if (dt === 'json' || dt === 'jsonb') base = {};
  else if (dt === 'enum') {
    const values = col.enumValues ? col.enumValues.split(',').map((v) => v.trim()).filter(Boolean) : [];
    base = values.length > 0 ? { enum: values } : { type: 'string' };
  } else if (dt === 'blob' || dt === 'bytea') base = { type: 'string', contentEncoding: 'base64' };
  else if (dt === 'array') base = { type: 'array' };
  else base = { type: 'string' };

  if (col.nullable) {
    if (base.type) return { ...base, type: [base.type, 'null'] };
    return { oneOf: [base, { type: 'null' }] };
  }
  return base;
}

function exportJsonSchema(entities: Entity[]): string {
  const definitions: Record<string, unknown> = {};
  for (const entity of entities) {
    const required: string[] = [];
    const properties: Record<string, unknown> = {};
    for (const col of [...entity.columns].sort((a, b) => a.order - b.order)) {
      const propSchema: Record<string, unknown> = { ...jsonSchemaType(col) };
      if (col.note) propSchema.description = col.note;
      if (col.defaultValue) propSchema.default = col.defaultValue;
      properties[col.name || `col_${col.id.slice(0, 6)}`] = propSchema;
      if (!col.nullable && !col.defaultValue) required.push(col.name || `col_${col.id.slice(0, 6)}`);
    }
    const schema: Record<string, unknown> = {
      type: 'object',
      properties,
    };
    if (required.length > 0) schema.required = required;
    if (entity.description) schema.description = entity.description;
    definitions[entity.name] = schema;
  }
  return JSON.stringify({
    $schema: 'http://json-schema.org/draft-07/schema#',
    title: 'Generated by surplan',
    definitions,
  }, null, 2);
}

