// ─── SQL Type Mapping ─────────────────────────────────────────────────────────

function toPostgresType(col: Column): string {
  switch (col.dataType) {
    case 'uuid': return 'UUID';
    case 'string': case 'varchar': return 'VARCHAR(255)';
    case 'char': return 'CHAR(1)';
    case 'text': return 'TEXT';
    case 'integer': case 'number': return 'INTEGER';
    case 'smallint': return 'SMALLINT';
    case 'bigint': return 'BIGINT';
    case 'float': return 'FLOAT';
    case 'decimal': case 'numeric': return 'DECIMAL(10, 2)';
    case 'boolean': return 'BOOLEAN';
    case 'date': return 'DATE';
    case 'datetime': case 'timestamp': return 'TIMESTAMP';
    case 'timestamptz': return 'TIMESTAMPTZ';
    case 'time': return 'TIME';
    case 'json': return 'JSON';
    case 'jsonb': return 'JSONB';
    case 'enum': {
      const vals = col.enumValues?.split(',').map((v) => `'${v.trim()}'`).filter(Boolean).join(', ');
      return vals ? `VARCHAR(50) CHECK (${col.name || 'col'} IN (${vals}))` : `VARCHAR(50) /* enum */`;
    }
    case 'blob': case 'bytea': return 'BYTEA';
    case 'array': return 'TEXT[]';
    default: return 'TEXT';
  }
}

function toMysqlType(col: Column): string {
  switch (col.dataType) {
    case 'uuid': return 'CHAR(36)';
    case 'string': case 'varchar': return 'VARCHAR(255)';
    case 'char': return 'CHAR(1)';
    case 'text': return 'TEXT';
    case 'integer': case 'number': return 'INT';
    case 'smallint': return 'SMALLINT';
    case 'bigint': return 'BIGINT';
    case 'float': return 'FLOAT';
    case 'decimal': case 'numeric': return 'DECIMAL(10, 2)';
    case 'boolean': return 'TINYINT(1)';
    case 'date': return 'DATE';
    case 'datetime': case 'timestamp': case 'timestamptz': return 'DATETIME';
    case 'time': return 'TIME';
    case 'json': case 'jsonb': return 'JSON';
    case 'enum': {
      const vals = col.enumValues?.split(',').map((v) => `'${v.trim()}'`).filter(Boolean).join(', ');
      return vals ? `ENUM(${vals})` : `ENUM(/* values */)`;
    }
    case 'blob': case 'bytea': return 'BLOB';
    default: return 'TEXT';
  }
}

function toSqliteType(col: Column): string {
  switch (col.dataType) {
    case 'integer': case 'smallint': case 'bigint': case 'number': return 'INTEGER';
    case 'float': case 'decimal': case 'numeric': return 'REAL';
    case 'boolean': return 'INTEGER';
    case 'json': case 'jsonb': case 'array': return 'TEXT';
    case 'blob': case 'bytea': return 'BLOB';
    default: return 'TEXT';
  }
}

// ─── SQL DDL Export ───────────────────────────────────────────────────────────

function exportSql(entities: Entity[], dialect: 'postgres' | 'mysql' | 'sqlite'): string {
  const lines: string[] = [];
  const q = dialect === 'mysql' ? '`' : '"';

  lines.push(`-- Generated by surplan`);
  lines.push(`-- Dialect: ${dialect}`);
  lines.push(`-- ${new Date().toISOString()}`);
  lines.push('');

  for (const entity of entities) {
    const tableName = entity.name || 'unnamed_table';
    if (entity.description) {
      lines.push(`-- ${entity.description}`);
    }
    lines.push(`CREATE TABLE ${q}${tableName}${q} (`);

    const cols = [...entity.columns].sort((a, b) => a.order - b.order);
    const colDefs: string[] = [];
    const constraints: string[] = [];

    for (const col of cols) {
      if (!col.name) continue;
      let typeFn = toPostgresType;
      if (dialect === 'mysql') typeFn = toMysqlType;
      if (dialect === 'sqlite') typeFn = toSqliteType;

      let def = `  ${q}${col.name}${q} ${typeFn(col)}`;
      if (!col.nullable) def += ' NOT NULL';
      if (col.unique) def += ' UNIQUE';
      if (col.defaultValue) {
        // Don't quote SQL function calls, keywords, or numeric values
        const isSqlExpr = /^\s*(\w+\s*\(|\d|true$|false$|null$|current_\w+$)/i.test(col.defaultValue.trim());
        const isStringType = !isSqlExpr && ['string', 'text', 'varchar', 'char', 'uuid', 'enum'].includes(col.dataType);
        def += ` DEFAULT ${isStringType ? `'${col.defaultValue}'` : col.defaultValue}`;
      }
      if (col.note) def += ` -- ${col.note}`;
      colDefs.push(def);
    }

    // Primary key constraint
    const pks = cols.filter((c) => c.primaryKey && c.name);
    if (pks.length > 0) {
      constraints.push(`  PRIMARY KEY (${pks.map((c) => `${q}${c.name}${q}`).join(', ')})`);
    }

    // FK constraints (postgres/mysql only)
    if (dialect !== 'sqlite') {
      for (const col of cols) {
        if (col.references && col.name && col.references.entityName && col.references.columnName) {
          constraints.push(
            `  CONSTRAINT fk_${tableName}_${col.name} FOREIGN KEY (${q}${col.name}${q}) REFERENCES ${q}${col.references.entityName}${q} (${q}${col.references.columnName}${q})`
          );
        }
      }
    }

    // CHECK constraints
    for (const col of cols) {
      if (col.check?.trim() && col.name) {
        constraints.push(`  CONSTRAINT chk_${tableName}_${col.name} CHECK (${col.check.trim()})`);
      }
    }

    lines.push([...colDefs, ...constraints].join(',\n'));
    lines.push(');');

    // Indexes
    for (const col of cols) {
      if (col.indexed && !col.primaryKey && col.name) {
        lines.push(`CREATE INDEX idx_${tableName}_${col.name} ON ${q}${tableName}${q} (${q}${col.name}${q});`);
      }
    }

    // COMMENT ON statements (PostgreSQL only)
    if (dialect === 'postgres') {
      if (entity.description) {
        lines.push(`COMMENT ON TABLE ${q}${tableName}${q} IS '${entity.description.replace(/'/g, "''")}';`);
      }
      for (const col of cols) {
        if (col.note && col.name) {
          lines.push(`COMMENT ON COLUMN ${q}${tableName}${q}.${q}${col.name}${q} IS '${col.note.replace(/'/g, "''")}';`);
        }
      }
    }

    lines.push('');
  }

  return lines.join('\n');
}

// ─── TypeScript Export ────────────────────────────────────────────────────────

function tsType(col: Column): string {
  switch (col.dataType) {
    case 'enum': {
      const vals = col.enumValues?.split(',').map((v) => `'${v.trim()}'`).filter(Boolean);
      return vals && vals.length > 0 ? vals.join(' | ') : 'string';
    }
    case 'uuid': case 'string': case 'varchar': case 'text': case 'char': return 'string';
    case 'integer': case 'smallint': case 'bigint': case 'float': case 'decimal': case 'numeric': case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'date': case 'datetime': case 'timestamp': case 'timestamptz': return 'Date';
    case 'time': return 'string';
    case 'json': case 'jsonb': return 'Record<string, unknown>';
    case 'array': return 'unknown[]';
    case 'blob': case 'bytea': return 'Buffer';
    default: return 'unknown';
  }
}

function toPascalCase(s: string): string {
  return s
    .split(/[_\s-]+/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');
}

function exportTypeScript(entities: Entity[]): string {
  const lines: string[] = [];
  lines.push('// Generated by surplan');
  lines.push(`// ${new Date().toISOString()}`);
  lines.push('');

  for (const entity of entities) {
    const interfaceName = toPascalCase(entity.name || 'Unknown');
    if (entity.description) {
      lines.push(`/** ${entity.description} */`);
    }
    lines.push(`export interface ${interfaceName} {`);
    const cols = [...entity.columns].sort((a, b) => a.order - b.order);
    for (const col of cols) {
      if (!col.name) continue;
      const opt = col.nullable ? '?' : '';
      const type = tsType(col) + (col.nullable ? ' | null' : '');
      if (col.note) lines.push(`  /** ${col.note} */`);
      lines.push(`  ${col.name}${opt}: ${type};`);
    }
    lines.push('}');
    lines.push('');
  }

  return lines.join('\n');
}

