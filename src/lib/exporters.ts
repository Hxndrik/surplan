function toSequelizeType(col: Column): string {
  switch (col.dataType) {
    case 'uuid': return 'DataTypes.UUID';
    case 'string': case 'varchar': return 'DataTypes.STRING';
    case 'char': return 'DataTypes.CHAR';
    case 'text': return 'DataTypes.TEXT';
    case 'integer': case 'number': return 'DataTypes.INTEGER';
    case 'smallint': return 'DataTypes.SMALLINT';
    case 'bigint': return 'DataTypes.BIGINT';
    case 'float': return 'DataTypes.FLOAT';
    case 'decimal': case 'numeric': return 'DataTypes.DECIMAL';
    case 'boolean': return 'DataTypes.BOOLEAN';
    case 'date': return 'DataTypes.DATEONLY';
    case 'datetime': case 'timestamp': case 'timestamptz': return 'DataTypes.DATE';
    case 'time': return 'DataTypes.TIME';
    case 'json': case 'jsonb': return 'DataTypes.JSON';
    case 'enum': {
      const vals = col.enumValues?.split(',').map((v) => `'${v.trim()}'`).filter(Boolean);
      return vals && vals.length > 0 ? `DataTypes.ENUM(${vals.join(', ')})` : 'DataTypes.STRING';
    }
    case 'blob': case 'bytea': return 'DataTypes.BLOB';
    case 'array': return 'DataTypes.ARRAY(DataTypes.TEXT)';
    default: return 'DataTypes.STRING';
  }
}

function exportSequelize(entities: Entity[]): string {
  const lines: string[] = [];
  lines.push(`import { DataTypes, Model, InferAttributes, InferCreationAttributes, CreationOptional, Sequelize } from 'sequelize';`);
  lines.push('');
  lines.push('// Generated by surplan');
  lines.push(`// ${new Date().toISOString()}`);
  lines.push('');
  lines.push(`const sequelize = new Sequelize(process.env.DATABASE_URL ?? 'sqlite::memory:');`);
  lines.push('');

  for (const entity of entities) {
    if (!entity.name) continue;
    const className = toPascalCase(entity.name);
    const cols = [...entity.columns].sort((a, b) => a.order - b.order).filter((c) => c.name);

    lines.push(`// ─── ${entity.name} ──────────────────────────────────────────`);
    if (entity.description) lines.push(`// ${entity.description}`);
    lines.push('');
    lines.push(`export class ${className} extends Model<`);
    lines.push(`  InferAttributes<${className}>,`);
    lines.push(`  InferCreationAttributes<${className}>`);
    lines.push(`> {`);

    for (const col of cols) {
      const t = tsType(col);
      if (col.nullable || col.primaryKey) {
        lines.push(`  declare ${col.name}: CreationOptional<${t}>;`);
      } else {
        lines.push(`  declare ${col.name}: ${t};`);
      }
    }

    lines.push('}');
    lines.push('');
    lines.push(`${className}.init(`);
    lines.push('  {');

    for (const col of cols) {
      const parts: string[] = [`type: ${toSequelizeType(col)}`];
      if (col.primaryKey) parts.push('primaryKey: true');
      if (col.dataType === 'uuid' && col.primaryKey) parts.push('defaultValue: DataTypes.UUIDV4');
      if (!col.nullable && !col.primaryKey) parts.push('allowNull: false');
      if (col.nullable) parts.push('allowNull: true');
      if (col.unique) parts.push('unique: true');
      if (col.defaultValue) {
        const isStr = ['string', 'varchar', 'text', 'char', 'uuid', 'enum'].includes(col.dataType);
        parts.push(`defaultValue: ${isStr ? `'${col.defaultValue}'` : col.defaultValue}`);
      }
      if (col.references) {
        parts.push(`references: { model: '${col.references.entityName}', key: '${col.references.columnName}' }`);
      }
      lines.push(`    ${col.name}: { ${parts.join(', ')} },`);
    }

    lines.push('  },');
    lines.push('  {');
    lines.push(`    tableName: '${entity.name}',`);
    lines.push('    sequelize,');
    lines.push('  }');
    lines.push(');');
    lines.push('');
  }

  return lines.join('\n').trimEnd();
}

