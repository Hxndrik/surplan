function exportMikroOrm(entities: Entity[]): string {
  const lines: string[] = [];
  lines.push('// Generated by surplan');
  lines.push(`// ${new Date().toISOString()}`);
  lines.push("import { Entity, PrimaryKey, Property, ManyToOne, OneToMany, Enum, Collection, Cascade } from '@mikro-orm/core';");
  lines.push('');

  const enumsEmitted = new Set<string>();
  entities.forEach((entity) => {
    entity.columns.forEach((col) => {
      if (col.dataType === 'enum' && col.enumValues?.trim()) {
        const enumName = `${toPascalCase(col.name)}Enum`;
        if (!enumsEmitted.has(enumName)) {
          enumsEmitted.add(enumName);
          const vals = col.enumValues.split(',').map((v) => v.trim()).filter(Boolean);
          lines.push(`export enum ${enumName} {`);
          vals.forEach((v) => lines.push(`  ${v.toUpperCase().replace(/\W+/g, '_')} = '${v}',`));
          lines.push('}');
          lines.push('');
        }
      }
    });
  });

  entities.forEach((entity) => {
    const className = toPascalCase(entity.name);
    const cols = [...entity.columns].sort((a, b) => a.order - b.order).filter((c) => c.name);
    if (entity.description) lines.push(`/** ${entity.description} */`);
    lines.push(`@Entity({ tableName: '${entity.name}' })`);
    lines.push(`export class ${className} {`);

    for (const col of cols) {
      const fieldName = snakeToCamel(col.name);
      const tsType = toMikroOrmTsType(col);
      const nullOpt = col.nullable ? ', nullable: true' : '';

      if (col.primaryKey) {
        if (col.dataType === 'uuid') {
          lines.push(`  @PrimaryKey({ type: 'uuid' })`);
        } else {
          lines.push(`  @PrimaryKey()`);
        }
        lines.push(`  ${fieldName}!: ${tsType};`);
      } else if (col.references) {
        const refClass = toPascalCase(col.references.entityName);
        const refField = snakeToCamel(col.references.entityName);
        lines.push(`  @ManyToOne(() => ${refClass}${col.nullable ? ', { nullable: true }' : ''})`);
        lines.push(`  ${refField}!: ${refClass};`);
      } else if (col.dataType === 'enum' && col.enumValues?.trim()) {
        const enumName = `${toPascalCase(col.name)}Enum`;
        lines.push(`  @Enum({ items: () => ${enumName}${nullOpt} })`);
        lines.push(`  ${fieldName}!: ${enumName};`);
      } else {
        const defaultPart = col.defaultValue ? `, default: ${/^\d+$/.test(col.defaultValue) ? col.defaultValue : `'${col.defaultValue}'`}` : '';
        lines.push(`  @Property({ columnType: '${col.dataType}'${nullOpt}${defaultPart} })`);
        lines.push(`  ${fieldName}!: ${tsType}${col.nullable ? ' | null' : ''};`);
      }
    }

    entities.forEach((other) => {
      if (other.id === entity.id) return;
      other.columns.forEach((col) => {
        if (col.references?.entityId === entity.id && col.name) {
          const otherClass = toPascalCase(other.name);
          const collField = snakeToCamel(other.name) + 's';
          const ownField = snakeToCamel(col.name.replace(/_id$/i, '')) || snakeToCamel(entity.name);
          lines.push(`  @OneToMany(() => ${otherClass}, (x) => x.${ownField}, { cascade: [Cascade.ALL] })`);
          lines.push(`  ${collField} = new Collection<${otherClass}>(this);`);
        }
      });
    });

    lines.push('}');
    lines.push('');
  });

  return lines.join('\n').trimEnd();
}

