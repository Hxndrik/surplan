function toTsType(col: Column): string {
  switch (col.dataType) {
    case 'uuid': case 'varchar': case 'string': case 'char': case 'text': return 'string';
    case 'integer': case 'smallint': case 'float': case 'decimal': case 'numeric': case 'number': return 'number';
    case 'bigint': return 'bigint';
    case 'boolean': return 'boolean';
    case 'date': case 'datetime': case 'timestamp': case 'timestamptz': return 'Date';
    case 'time': return 'string';
    case 'json': case 'jsonb': return 'Record<string, unknown>';
    case 'enum': {
      if (col.enumValues?.trim()) {
        const vals = col.enumValues.split(',').map((v) => `'${v.trim()}'`).filter(Boolean);
        return vals.join(' | ');
      }
      return 'string';
    }
    case 'array': return 'unknown[]';
    default: return 'unknown';
  }
}

function buildTypeOrmColumn(col: Column): { decorator: string; propType: string } {
  const type = toTypeOrmType(col);
  const tsType = toTsType(col);
  const nullable = col.nullable ? ', nullable: true' : '';

  if (col.primaryKey) {
    if (col.dataType === 'uuid') {
      return { decorator: `@PrimaryGeneratedColumn('uuid')`, propType: tsType };
    }
    return { decorator: `@PrimaryGeneratedColumn()`, propType: tsType };
  }

  if (col.dataType === 'enum' && col.enumValues?.trim()) {
    const enumName = `${toPascalCase(col.name)}Enum`;
    const vals = col.enumValues.split(',').map((v) => v.trim()).filter(Boolean);
    const enumStr = vals.map((v) => `${v.toUpperCase().replace(/[^A-Z0-9_]/g, '_')}: '${v}'`).join(', ');
    const defaultStr = col.defaultValue ? `, default: '${col.defaultValue}'` : '';
    return {
      decorator: `// enum ${enumName} = { ${enumStr} }\n  @Column({ type: 'enum', enum: ${enumName}${defaultStr}${nullable} })`,
      propType: tsType,
    };
  }

  const opts: string[] = [`type: '${type}'`];
  if (col.unique) opts.push('unique: true');
  if (col.nullable) opts.push('nullable: true');
  if (col.defaultValue) {
    const dv = col.defaultValue.trim();
    const numTypes = ['integer', 'smallint', 'bigint', 'float', 'decimal', 'numeric', 'number'];
    if (numTypes.includes(col.dataType) || col.dataType === 'boolean') {
      opts.push(`default: ${dv}`);
    } else {
      opts.push(`default: '${dv}'`);
    }
  }

  const isCreatedAt = col.name === 'created_at' || col.name === 'createdAt';
  const isUpdatedAt = col.name === 'updated_at' || col.name === 'updatedAt';
  if (isCreatedAt && (col.dataType === 'timestamp' || col.dataType === 'timestamptz')) {
    return { decorator: '@CreateDateColumn()', propType: tsType };
  }
  if (isUpdatedAt && (col.dataType === 'timestamp' || col.dataType === 'timestamptz')) {
    return { decorator: '@UpdateDateColumn()', propType: tsType };
  }

  const optsStr = opts.length > 1 ? `{ ${opts.join(', ')} }` : `{ type: '${type}'${nullable} }`;
  return { decorator: `@Column(${optsStr})`, propType: tsType };
}

function exportTypeOrm(entities: Entity[]): string {
  const lines: string[] = [];

  // Collect needed imports
  const coreImports = new Set<string>(['Entity', 'Column']);
  entities.forEach((entity) => {
    entity.columns.forEach((col) => {
      if (col.primaryKey) {
        coreImports.add('PrimaryGeneratedColumn');
      }
      if ((col.name === 'created_at' || col.name === 'createdAt') && (col.dataType === 'timestamp' || col.dataType === 'timestamptz')) {
        coreImports.add('CreateDateColumn');
      }
      if ((col.name === 'updated_at' || col.name === 'updatedAt') && (col.dataType === 'timestamp' || col.dataType === 'timestamptz')) {
        coreImports.add('UpdateDateColumn');
      }
      if (col.references) {
        coreImports.add('ManyToOne');
        coreImports.add('JoinColumn');
      }
      if (col.check?.trim()) {
        coreImports.add('Check');
      }
    });
  });

  lines.push(`import { ${[...coreImports].sort().join(', ')} } from 'typeorm';`);
  lines.push('');
  lines.push('// Generated by surplan');
  lines.push(`// ${new Date().toISOString()}`);
  lines.push('');

  entities.forEach((entity) => {
    const className = toPascalCase(entity.name);
    if (entity.description) lines.push(`// ${entity.description}`);
    entity.columns.filter((c) => c.check?.trim() && c.name).forEach((col) => {
      lines.push(`@Check('chk_${entity.name}_${col.name}', '${col.check!.trim().replace(/'/g, "\\'")}')`);
    });
    lines.push(`@Entity('${entity.name}')`);
    lines.push(`export class ${className} {`);

    entity.columns.forEach((col) => {
      const key = snakeToCamel(col.name) || col.name;
      const { decorator, propType } = buildTypeOrmColumn(col);
      lines.push(`  ${decorator}`);
      const nullable = col.nullable && !col.primaryKey ? '?' : '!';
      lines.push(`  ${key}${nullable}: ${propType};`);
      lines.push('');
    });

    // FK relations
    entity.columns.forEach((col) => {
      if (!col.references) return;
      const refClass = toPascalCase(col.references.entityName);
      const propName = snakeToCamel(col.references.entityName.toLowerCase());
      lines.push(`  @ManyToOne(() => ${refClass}, { nullable: ${col.nullable} })`);
      lines.push(`  @JoinColumn({ name: '${col.name}' })`);
      lines.push(`  ${propName}!: ${refClass};`);
      lines.push('');
    });

    // Remove trailing blank line inside class
    if (lines[lines.length - 1] === '') lines.pop();
    lines.push('}');
    lines.push('');
  });

  return lines.join('\n').trimEnd();
}

function toGqlType(col: Column): string {
  let base: string;
  switch (col.dataType) {
    case 'integer':
    case 'bigint':
    case 'smallint':
    case 'number':
      base = 'Int'; break;
    case 'float':
    case 'decimal':
    case 'numeric':
      base = 'Float'; break;
    case 'boolean':
      base = 'Boolean'; break;
    case 'json':
    case 'jsonb':
      base = 'JSON'; break;
    case 'array':
      base = '[String]'; break;
    case 'enum':
      base = col.enumValues.trim() ? `${toPascalCase(col.name)}Enum` : 'String'; break;
    default:
      base = 'String';
  }
  if (col.primaryKey) base = 'ID';
  return col.nullable ? base : `${base}!`;
}

function exportGraphQL(entities: Entity[]): string {
  const lines: string[] = [];
  lines.push('# Generated by surplan');
  lines.push(`# ${new Date().toISOString()}`);
  lines.push('');

  const hasJson = entities.some((e) => e.columns.some((c) => c.dataType === 'json' || c.dataType === 'jsonb'));
  if (hasJson) { lines.push('scalar JSON'); lines.push(''); }

  // Collect + deduplicate enums
  const seenEnums = new Set<string>();
  entities.forEach((entity) => {
    entity.columns.forEach((col) => {
      if (col.dataType === 'enum' && col.enumValues.trim()) {
        const enumName = `${toPascalCase(col.name)}Enum`;
        if (!seenEnums.has(enumName)) {
          seenEnums.add(enumName);
          const values = col.enumValues.split(',')
            .map((v) => v.trim().toUpperCase().replace(/\W+/g, '_'))
            .filter(Boolean);
          lines.push(`enum ${enumName} {`);
          values.forEach((v) => lines.push(`  ${v}`));
          lines.push('}');
          lines.push('');
        }
      }
    });
  });

  // Types
  entities.forEach((entity) => {
    const typeName = toPascalCase(entity.name);
    if (entity.description) lines.push(`"""${entity.description}"""`);
    lines.push(`type ${typeName} {`);
    entity.columns.forEach((col) => {
      const fieldName = snakeToCamel(col.name) || col.name;
      const note = col.note ? ` # ${col.note}` : '';
      lines.push(`  ${fieldName}: ${toGqlType(col)}${note}`);
    });
    // Relation fields for FK columns
    entity.columns.forEach((col) => {
      if (col.references) {
        const refType = toPascalCase(col.references.entityName);
        const relField = snakeToCamel(col.references.entityName.toLowerCase());
        lines.push(`  ${relField}: ${refType}${col.nullable ? '' : '!'}`);
      }
    });
    lines.push('}');
    lines.push('');
  });

  // Input types
  entities.forEach((entity) => {
    const typeName = toPascalCase(entity.name);
    const inputCols = entity.columns.filter((c) => !c.primaryKey);
    if (inputCols.length === 0) return;
    lines.push(`input Create${typeName}Input {`);
    inputCols.forEach((col) => {
      const fieldName = snakeToCamel(col.name) || col.name;
      lines.push(`  ${fieldName}: ${toGqlType(col)}`);
    });
    lines.push('}');
    lines.push('');
    lines.push(`input Update${typeName}Input {`);
    inputCols.forEach((col) => {
      const fieldName = snakeToCamel(col.name) || col.name;
      const t = toGqlType(col);
      const optional = t.endsWith('!') ? t.slice(0, -1) : t;
      lines.push(`  ${fieldName}: ${optional}`);
    });
    lines.push('}');
    lines.push('');
  });

  // Query + Mutation roots
  if (entities.length > 0) {
    lines.push('type Query {');
    entities.forEach((entity) => {
      const typeName = toPascalCase(entity.name);
      const plural = `${snakeToCamel(entity.name)}s`;
      const singular = snakeToCamel(entity.name);
      lines.push(`  ${singular}(id: ID!): ${typeName}`);
      lines.push(`  ${plural}: [${typeName}!]!`);
    });
    lines.push('}');
    lines.push('');
    lines.push('type Mutation {');
    entities.forEach((entity) => {
      const typeName = toPascalCase(entity.name);
      lines.push(`  create${typeName}(input: Create${typeName}Input!): ${typeName}!`);
      lines.push(`  update${typeName}(id: ID!, input: Update${typeName}Input!): ${typeName}`);
      lines.push(`  delete${typeName}(id: ID!): Boolean!`);
    });
    lines.push('}');
  }

  return lines.join('\n').trimEnd();
}

