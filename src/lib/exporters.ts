function prismaType(col: Column): string {
  switch (col.dataType) {
    case 'enum': return toPascalCase(col.name || 'Enum'); // Prisma uses named enum types
    case 'uuid': case 'string': case 'varchar': case 'text': case 'char': return 'String';
    case 'integer': case 'smallint': case 'number': return 'Int';
    case 'bigint': return 'BigInt';
    case 'float': return 'Float';
    case 'decimal': case 'numeric': return 'Decimal';
    case 'boolean': return 'Boolean';
    case 'date': return 'DateTime';
    case 'datetime': case 'timestamp': case 'timestamptz': return 'DateTime';
    case 'time': return 'String';
    case 'json': case 'jsonb': return 'Json';
    case 'array': return 'String[]';
    case 'blob': case 'bytea': return 'Bytes';
    default: return 'String';
  }
}

function toCamelCase(s: string): string {
  return s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
}

function prismaDbAnnotation(col: Column): string | null {
  switch (col.dataType) {
    case 'uuid': return '@db.Uuid';
    case 'text': return '@db.Text';
    case 'varchar': case 'string': return '@db.VarChar(255)';
    case 'char': return '@db.Char(1)';
    case 'smallint': return '@db.SmallInt';
    case 'bigint': return '@db.BigInt';
    case 'decimal': case 'numeric': return '@db.Decimal(10, 2)';
    case 'timestamptz': return '@db.Timestamptz(3)';
    case 'jsonb': return '@db.JsonB';
    case 'bytea': case 'blob': return '@db.ByteA';
    default: return null;
  }
}

function exportPrisma(entities: Entity[]): string {
  const lines: string[] = [];
  lines.push('// Generated by surplan');
  lines.push(`// ${new Date().toISOString()}`);
  lines.push('');
  lines.push('generator client {');
  lines.push('  provider = "prisma-client-js"');
  lines.push('}');
  lines.push('');
  lines.push('datasource db {');
  lines.push('  provider = "postgresql"');
  lines.push('  url      = env("DATABASE_URL")');
  lines.push('}');
  lines.push('');

  // Emit Prisma enum declarations for enum columns
  const enumCols = entities.flatMap((e) =>
    e.columns.filter((c) => c.dataType === 'enum' && c.name && c.enumValues?.trim())
  );
  if (enumCols.length > 0) {
    const seen = new Set<string>();
    for (const col of enumCols) {
      const enumName = toPascalCase(col.name);
      if (seen.has(enumName)) continue;
      seen.add(enumName);
      const vals = col.enumValues.split(',').map((v) => v.trim()).filter(Boolean);
      if (vals.length === 0) continue;
      lines.push(`enum ${enumName} {`);
      vals.forEach((v) => lines.push(`  ${v.toUpperCase().replace(/\s+/g, '_')}`));
      lines.push('}');
      lines.push('');
    }
  }

  for (const entity of entities) {
    const modelName = toPascalCase(entity.name || 'Unknown');
    const tableName = entity.name || 'unknown_table';
    if (entity.description) {
      lines.push(`/// ${entity.description}`);
    }
    lines.push(`model ${modelName} {`);

    const cols = [...entity.columns].sort((a, b) => a.order - b.order);
    const blockAttrs: string[] = []; // @@index, @@unique multi, @@map

    // Collect relation targets for reverse relation fields
    const relationFields: { name: string; type: string; attr: string }[] = [];

    for (const col of cols) {
      if (!col.name) continue;
      const fieldName = toCamelCase(col.name);
      const isCamelMapped = fieldName !== col.name;
      let type = prismaType(col);
      if (col.nullable) type += '?';

      const attrs: string[] = [];
      if (col.primaryKey) attrs.push('@id');
      if (col.dataType === 'uuid' && col.primaryKey) attrs.push('@default(uuid())');
      if (col.unique) attrs.push('@unique');
      if (col.defaultValue && !col.primaryKey) {
        const needsQuotes = ['string', 'varchar', 'text', 'char'].includes(col.dataType);
        const val = col.defaultValue;
        if (needsQuotes && !val.startsWith('"') && !val.startsWith("'") && val !== 'now()' && !val.startsWith('auto'))
          attrs.push(`@default("${val}")`);
        else
          attrs.push(`@default(${val})`);
      }
      const dbAnnotation = prismaDbAnnotation(col);
      if (dbAnnotation) attrs.push(dbAnnotation);
      if (isCamelMapped) attrs.push(`@map("${col.name}")`);

      if (col.references?.entityName) {
        const relName = toCamelCase(col.references.entityName);
        const relModel = toPascalCase(col.references.entityName);
        const refField = toCamelCase(col.references.columnName);
        attrs.push(`@relation("${relModel}To${modelName}", fields: [${fieldName}], references: [${refField}])`);
        // Add reverse relation field
        const reverseType = col.nullable ? `${relModel}?` : relModel;
        relationFields.push({
          name: relName,
          type: reverseType,
          attr: `@relation("${relModel}To${modelName}")`,
        });
      }

      if (col.note) lines.push(`  /// ${col.note}`);
      lines.push(`  ${fieldName.padEnd(20)} ${type.padEnd(12)} ${attrs.join(' ')}`.trimEnd());

      // Block-level index
      if (col.indexed && !col.primaryKey) {
        blockAttrs.push(`@@index([${fieldName}])`);
      }
    }

    // Reverse relation fields
    if (relationFields.length > 0) {
      lines.push('');
      for (const rf of relationFields) {
        lines.push(`  ${rf.name.padEnd(20)} ${rf.type.padEnd(12)} ${rf.attr}`);
      }
    }

    // @@map for snake_case table names
    if (tableName.includes('_') || tableName !== tableName.toLowerCase()) {
      blockAttrs.push(`@@map("${tableName}")`);
    }

    if (blockAttrs.length > 0) {
      lines.push('');
      blockAttrs.forEach((a) => lines.push(`  ${a}`));
    }

    lines.push('}');
    lines.push('');
  }

  return lines.join('\n');
}

// ─── Mermaid ER Diagram ───────────────────────────────────────────────────────

function exportMermaid(entities: Entity[]): string {
  const lines: string[] = [];
  lines.push('erDiagram');
  lines.push('');

  for (const entity of entities) {
    if (!entity.name) continue;
    lines.push(`  ${entity.name} {`);
    const cols = [...entity.columns].sort((a, b) => a.order - b.order);
    for (const col of cols) {
      if (!col.name) continue;
      const typeStr = col.dataType.toUpperCase();
      const pkTag = col.primaryKey ? ' PK' : col.unique ? ' UK' : col.references ? ' FK' : '';
      lines.push(`    ${typeStr} ${col.name}${pkTag}`);
    }
    lines.push('  }');
    lines.push('');
  }

  // Relationships
  for (const entity of entities) {
    if (!entity.name) continue;
    for (const col of entity.columns) {
      if (col.references?.entityName) {
        lines.push(`  ${col.references.entityName} ||--o{ ${entity.name} : "has"`);
      }
    }
  }

  return lines.join('\n');
}

