function toMongooseType(col: Column): string {
  switch (col.dataType) {
    case 'uuid': case 'string': case 'varchar': case 'text': case 'char': return 'String';
    case 'integer': case 'smallint': case 'bigint': case 'float': case 'decimal': case 'numeric': case 'number': return 'Number';
    case 'boolean': return 'Boolean';
    case 'date': case 'datetime': case 'timestamp': case 'timestamptz': return 'Date';
    case 'time': return 'String';
    case 'json': case 'jsonb': return 'Schema.Types.Mixed';
    case 'array': return '[Schema.Types.Mixed]';
    case 'blob': case 'bytea': return 'Buffer';
    case 'enum': return 'String';
    default: return 'String';
  }
}

function exportMongoose(entities: Entity[]): string {
  const lines: string[] = [];
  lines.push(`import { Schema, model } from 'mongoose';`);
  lines.push('');
  lines.push('// Generated by surplan');
  lines.push(`// ${new Date().toISOString()}`);
  lines.push('');

  for (const entity of entities) {
    if (!entity.name) continue;
    const className = toPascalCase(entity.name);
    const cols = [...entity.columns].sort((a, b) => a.order - b.order).filter((c) => c.name);
    const dataCols = cols.filter((c) => !c.primaryKey);

    lines.push(`// ─── ${entity.name} ──────────────────────────────────────────`);
    if (entity.description) lines.push(`// ${entity.description}`);
    lines.push('');
    lines.push(`export interface I${className} {`);
    for (const col of dataCols) {
      lines.push(`  ${col.name}${col.nullable ? '?' : ''}: ${tsType(col)};`);
    }
    lines.push('}');
    lines.push('');
    lines.push(`const ${entity.name}Schema = new Schema<I${className}>({`);

    for (const col of dataCols) {
      const parts: string[] = [];
      if (col.references) {
        parts.push('type: Schema.Types.ObjectId');
        parts.push(`ref: '${toPascalCase(col.references.entityName)}'`);
      } else {
        parts.push(`type: ${toMongooseType(col)}`);
      }
      if (!col.nullable) parts.push('required: true');
      if (col.unique) parts.push('unique: true');
      if (col.indexed && !col.unique) parts.push('index: true');
      if (col.defaultValue) {
        const isStr = ['string', 'varchar', 'text', 'char', 'uuid', 'enum'].includes(col.dataType);
        parts.push(`default: ${isStr ? `'${col.defaultValue}'` : col.defaultValue}`);
      }
      if (col.dataType === 'enum' && col.enumValues) {
        const vals = col.enumValues.split(',').map((v) => `'${v.trim()}'`).filter(Boolean);
        if (vals.length > 0) parts.push(`enum: [${vals.join(', ')}]`);
      }
      lines.push(`  ${col.name}: { ${parts.join(', ')} },`);
    }

    lines.push('}, { timestamps: true });');
    lines.push('');
    lines.push(`export const ${className} = model<I${className}>('${className}', ${entity.name}Schema);`);
    lines.push('');
  }

  return lines.join('\n').trimEnd();
}

