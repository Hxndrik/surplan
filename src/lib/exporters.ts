  lines.push('');
  lines.push('from __future__ import annotations');
  lines.push('');
  const pyImports: string[] = ['Optional'];
  if (usesDatetime) pyImports.push('datetime');
  if (usesDate) pyImports.push('date');
  lines.push(`from typing import ${pyImports.join(', ')}`);
  if (usesUuid) lines.push('import uuid as uuid_lib');
  lines.push('');

  const usesCheck = entities.some((e) => e.columns.some((c) => c.check?.trim()));
  const saTypes = new Set(['Column', 'ForeignKey', 'String', 'Integer', 'Text', 'Boolean', 'Float', 'Numeric', 'JSON']);
  if (usesUuid) saTypes.add('Uuid');
