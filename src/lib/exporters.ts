// ─── Sample INSERT Generation ─────────────────────────────────────────────────

function sampleValue(col: Column): string {
  if (col.defaultValue) return col.defaultValue;
  if (col.nullable) return 'NULL';
  switch (col.dataType) {
    case 'uuid': return `gen_random_uuid()`;
    case 'string': case 'varchar': case 'text': case 'char': return `'sample_${col.name}'`;
    case 'integer': case 'smallint': case 'bigint': case 'number': return '1';
    case 'float': case 'decimal': case 'numeric': return '1.0';
    case 'boolean': return 'true';
    case 'date': return `'2024-01-01'`;
    case 'datetime': case 'timestamp': case 'timestamptz': return `now()`;
    case 'time': return `'12:00:00'`;
    case 'json': case 'jsonb': return `'{}'`;
    case 'enum': return `'value'`;
    case 'array': return `'{}'`;
    default: return `'value'`;
  }
}

export function exportEntitySampleInsert(entity: Entity): string {
  const insertCols = entity.columns.filter((c) => !c.primaryKey || c.dataType !== 'uuid');
  if (insertCols.length === 0) return `-- No insertable columns on ${entity.name}`;
  const cols = insertCols.map((c) => c.name || 'column').join(', ');
  const vals = insertCols.map((c) => sampleValue(c)).join(', ');
  return `INSERT INTO ${entity.name} (${cols})\nVALUES (${vals});`;
}

// ─── Main Export Function ─────────────────────────────────────────────────────

export function exportEntityMarkdownTable(entity: Entity): string {
  const header = `### ${entity.name}\n`;
  const desc = entity.description ? `${entity.description}\n\n` : '';
  const tableHeader = '| Column | Type | PK | Nullable | Default | Note |\n| --- | --- | --- | --- | --- | --- |';
  const rows = entity.columns.map((col) =>
    `| ${col.name} | \`${col.dataType}\` | ${col.primaryKey ? '✓' : ''} | ${col.nullable ? '✓' : ''} | ${col.defaultValue || ''} | ${col.note || ''} |`
  ).join('\n');
  return header + desc + tableHeader + '\n' + rows;
}

// ─── Zod Schema Export ────────────────────────────────────────────────────────

function zodType(col: Column): string {
  let base: string;
  switch (col.dataType) {
    case 'uuid': base = 'z.string().uuid()'; break;
    case 'enum': {
      const vals = col.enumValues?.split(',').map((v) => v.trim()).filter(Boolean);
      base = vals && vals.length > 0 ? `z.enum([${vals.map((v) => `'${v}'`).join(', ')}])` : 'z.string()';
      break;
    }
    case 'string': case 'varchar': case 'text': case 'char': base = 'z.string()'; break;
    case 'integer': case 'smallint': case 'bigint': case 'number': base = 'z.number().int()'; break;
    case 'float': case 'decimal': case 'numeric': base = 'z.number()'; break;
    case 'boolean': base = 'z.boolean()'; break;
    case 'date': base = 'z.string().date()'; break;
    case 'datetime': case 'timestamp': case 'timestamptz': base = 'z.string().datetime()'; break;
    case 'time': base = 'z.string()'; break;
    case 'json': case 'jsonb': base = 'z.record(z.string(), z.unknown())'; break;
    case 'array': base = 'z.array(z.unknown())'; break;
    default: base = 'z.unknown()';
  }
  if (col.nullable) base += '.nullable()';
  if (col.nullable) base += '.optional()';
  return base;
}

export function exportEntityZodSchema(entity: Entity): string {
  const schemaName = toPascalCase(entity.name || 'Unknown') + 'Schema';
  const cols = [...entity.columns].sort((a, b) => a.order - b.order).filter((c) => c.name);
  const lines: string[] = [];
  lines.push(`import { z } from 'zod';`);
  lines.push('');
  if (entity.description) lines.push(`// ${entity.description}`);
  lines.push(`export const ${schemaName} = z.object({`);
  for (const col of cols) {
    const commentParts = [col.note, col.check?.trim() ? `CHECK: ${col.check.trim()}` : ''].filter(Boolean);
    const comment = commentParts.length > 0 ? ` // ${commentParts.join(' | ')}` : '';
    lines.push(`  ${col.name}: ${zodType(col)},${comment}`);
  }
  lines.push('});');
  lines.push('');
  lines.push(`export type ${toPascalCase(entity.name || 'Unknown')} = z.infer<typeof ${schemaName}>;`);
  return lines.join('\n');
}

function exportDbml(entities: Entity[]): string {
  const lines: string[] = [];
  lines.push('// Generated by surplan — https://dbdiagram.io compatible DBML');
  lines.push('');

  // Collect FK references to render as Ref blocks after tables
  const refs: string[] = [];

  for (const entity of entities) {
    lines.push(`Table ${entity.name} {`);

    for (const col of entity.columns) {
      let typeStr = col.dataType.toUpperCase();
      if (col.dataType === 'enum' && col.enumValues?.trim()) {
        typeStr = `varchar(50)`;
      }
      const settings: string[] = [];
      if (col.primaryKey) settings.push('pk');
      if (!col.nullable && !col.primaryKey) settings.push('not null');
      if (col.unique && !col.primaryKey) settings.push('unique');
      if (col.defaultValue) settings.push(`default: \`${col.defaultValue}\``);
      const noteText = [
        col.note,
        col.check ? `CHECK: ${col.check}` : '',
        col.indexed && !col.primaryKey ? 'indexed' : '',
      ].filter(Boolean).join(' | ');
      if (noteText) settings.push(`note: '${noteText.replace(/'/g, "\\'")}'`);

      const settingsStr = settings.length > 0 ? ` [${settings.join(', ')}]` : '';
      lines.push(`  ${col.name} ${typeStr}${settingsStr}`);

      if (col.references) {
        refs.push(`Ref: ${entity.name}.${col.name} > ${col.references.entityName}.${col.references.columnName}`);
      }
    }

    if (entity.description) {
      lines.push(`  Note: '${entity.description.replace(/'/g, "\\'")}'`);
    }

    // Indexes block for indexed/composite keys
    const indexedCols = entity.columns.filter((c) => c.indexed && !c.primaryKey && c.name);
    if (indexedCols.length > 0) {
      lines.push('');
      lines.push('  indexes {');
      for (const ic of indexedCols) {
        const indexAttr = ic.unique ? ' [unique]' : '';
        lines.push(`    ${ic.name}${indexAttr}`);
      }
      lines.push('  }');
    }

    lines.push('}');
    lines.push('');
  }

  if (refs.length > 0) {
    lines.push('// Relationships');
    refs.forEach((r) => lines.push(r));
  }

  return lines.join('\n').trimEnd();
}

