export function exportFeaturesCSV(): void {
  const ps = useProjectStore.getState();
  const es = useEntityStore.getState();
  const { features, milestones, meta } = ps;
  const { entities } = es;

  const milestoneMap = new Map(milestones.map((m) => [m.id, m.name]));
  const entityMap = new Map(entities.map((e) => [e.id, e.name]));

  const escape = (val: string) => `"${val.replace(/"/g, '""')}"`;

  const header = ['Title', 'Status', 'Kind', 'Priority', 'Estimate', 'Value', 'Sprint', 'Start Date', 'Due Date', 'Completed At', 'Milestone', 'Tags', 'Entity Refs', 'Notes', 'URL', 'Assignee', 'Checklist'];
  const rows = features.map((f) => [
    escape(f.title),
    f.done ? 'done' : f.inProgress ? 'in-progress' : 'todo',
    f.kind ?? 'feature',
    f.priority,
    f.estimate ?? '',
    f.value ?? '',
    escape(f.sprint ?? ''),
    f.startDate ?? '',
    f.dueDate ?? '',
    f.completedAt ?? '',
    escape(f.milestone ? (milestoneMap.get(f.milestone) ?? f.milestone) : ''),
    escape((f.tags ?? []).join(', ')),
    escape((f.entityRefs ?? []).map((id) => entityMap.get(id) ?? id).join(', ')),
    escape(f.notes ?? ''),
    escape(f.url ?? ''),
    escape(f.assignee ?? ''),
    escape((f.checklist ?? []).map((c) => `[${c.done ? 'x' : ' '}] ${c.text}`).join(' | ')),
  ]);

  const csv = [header.join(','), ...rows.map((r) => r.join(','))].join('\n');
  const blob = new Blob([csv], { type: 'text/csv' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${(meta.name || 'surplan-project').replace(/\s+/g, '-').toLowerCase()}-features.csv`;
  a.click();
  URL.revokeObjectURL(url);
}

// ─── Feature CSV Import ─────────────────────────────────────────────────────────

const IMPORT_MILESTONE_COLORS = [
  '#6366f1', '#8b5cf6', '#10b981', '#f59e0b', '#ef4444', '#06b6d4', '#ec4899', '#64748b',
];

/** Parse a single CSV line respecting quoted fields */
function parseCSVLine(line: string): string[] {
  const result: string[] = [];
  let cur = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') {
      if (inQuotes && line[i + 1] === '"') { cur += '"'; i++; }
      else inQuotes = !inQuotes;
    } else if (ch === ',' && !inQuotes) {
      result.push(cur); cur = '';
    } else {
      cur += ch;
    }
  }
  result.push(cur);
  return result;
}

export function importFeaturesCSV(file: File): Promise<{ success: boolean; message: string; count?: number }> {
  return new Promise((resolve) => {
    const reader = new FileReader();
    reader.onload = (e) => {
      try {
        const text = e.target?.result as string;
        const lines = text.split('\n').map((l) => l.trim()).filter(Boolean);
        if (lines.length < 2) {
          resolve({ success: false, message: 'CSV has no data rows' });
          return;
        }

        const headers = parseCSVLine(lines[0]).map((h) =>
          h.toLowerCase().replace(/\s+/g, '').replace(/[^a-z]/g, '')
        );
        const getCol = (row: string[], name: string) => {
          const idx = headers.indexOf(name);
          return idx >= 0 ? (row[idx]?.trim() ?? '') : '';
        };

        const ps = useProjectStore.getState();
        const es = useEntityStore.getState();

        const milestoneByName = new Map(ps.milestones.map((m) => [m.name.toLowerCase(), m.id]));
        const entityByName = new Map(es.entities.map((e) => [e.name.toLowerCase(), e.id]));

        const newMilestones: Milestone[] = [];
        const getMilestoneId = (name: string): string => {
          if (!name) return '';
          const lower = name.toLowerCase();
          if (milestoneByName.has(lower)) return milestoneByName.get(lower)!;
          const already = newMilestones.find((m) => m.name.toLowerCase() === lower);
          if (already) return already.id;
          const id = createId();
          const color = IMPORT_MILESTONE_COLORS[(ps.milestones.length + newMilestones.length) % IMPORT_MILESTONE_COLORS.length];
          newMilestones.push({ id, name, description: '', color });
          milestoneByName.set(lower, id);
          return id;
        };

        const VALID_PRIORITIES = new Set<Priority>(['critical', 'high', 'medium', 'low', 'nice-to-have']);
        const VALID_ESTIMATES = new Set<Estimate>(['', '1', '2', '3', '5', '8', '13', '?']);

        const newFeatures: Feature[] = [];
        for (let i = 1; i < lines.length; i++) {
          const row = parseCSVLine(lines[i]);
          const title = getCol(row, 'title');
          if (!title) continue;

          const statusRaw = getCol(row, 'status').toLowerCase();
          const done = statusRaw === 'done';
          const inProgress = !done && (statusRaw === 'in-progress' || statusRaw === 'inprogress' || statusRaw === 'active');

          const priorityRaw = getCol(row, 'priority').toLowerCase() as Priority;
          const priority: Priority = VALID_PRIORITIES.has(priorityRaw) ? priorityRaw : 'medium';

          const estimateRaw = getCol(row, 'estimate') as Estimate;
          const estimate: Estimate = VALID_ESTIMATES.has(estimateRaw) ? estimateRaw : '';

          const valueRaw = getCol(row, 'value') as Estimate;
          const value: Estimate | undefined = VALID_ESTIMATES.has(valueRaw) ? valueRaw : undefined;

          const tagsRaw = getCol(row, 'tags');
          const tags = tagsRaw ? tagsRaw.split(',').map((t) => t.trim().toLowerCase()).filter(Boolean) : [];

          const entityRefsRaw = getCol(row, 'entityrefs');
          const entityRefs = entityRefsRaw
            ? entityRefsRaw.split(',').map((n) => n.trim().toLowerCase()).filter(Boolean)
                .map((name) => entityByName.get(name)).filter((id): id is string => !!id)
            : [];

          const startDate = getCol(row, 'startdate') || undefined;
          const dueDate = getCol(row, 'duedate') || undefined;
          const completedAt = getCol(row, 'completedat') || undefined;
          const url = getCol(row, 'url') || undefined;
          const notes = getCol(row, 'notes') || '';
          const milestone = getMilestoneId(getCol(row, 'milestone'));
          const assignee = getCol(row, 'assignee') || undefined;

          newFeatures.push({
            id: createId(),
            title,
            description: '',
            priority,
            estimate,
            value,
            done,
            inProgress,
            entityRefs,
            milestone,
            tags,
            notes,
            blockedBy: [],
            startDate,
            dueDate,
            completedAt,
            url,
            assignee,
          });
        }

        if (newFeatures.length === 0) {
          resolve({ success: false, message: 'No valid features found in CSV' });
          return;
        }

        useProjectStore.setState((state) => ({
          features: [...state.features, ...newFeatures],
          milestones: [...state.milestones, ...newMilestones],
        }));

        resolve({
          success: true,
          count: newFeatures.length,
          message: `Imported ${newFeatures.length} feature${newFeatures.length !== 1 ? 's' : ''}${
            newMilestones.length > 0
              ? ` · created ${newMilestones.length} milestone${newMilestones.length !== 1 ? 's' : ''}`
              : ''
          }`,
        });
      } catch {
        resolve({ success: false, message: 'Failed to parse CSV file' });
      }
    };
    reader.readAsText(file);
  });
}

