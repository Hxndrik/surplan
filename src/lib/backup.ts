// ─── GitHub Issues Markdown Export ─────────────────────────────────────────────

const PRIORITY_LABEL: Record<Priority, string> = {
  critical: '🔴 Critical',
  high: '🟠 High',
  medium: '🟡 Medium',
  low: '🔵 Low',
  'nice-to-have': '⚪ Nice-to-have',
};

export function exportGithubIssues(): void {
  const ps = useProjectStore.getState();
  const { features, milestones, meta } = ps;

  const milestoneMap = new Map(milestones.map((m) => [m.id, m]));
  const featureMap = new Map(features.map((f) => [f.id, f]));
  const slug = (meta.name || 'surplan-project').replace(/\s+/g, '-').toLowerCase();

  const lines: string[] = [];
  lines.push(`# ${meta.name || 'Project'} — GitHub Issues`);
  lines.push('');
  lines.push(`> Exported ${new Date().toLocaleDateString()} from surplan`);
  lines.push('');

  // Group by milestone
  const byMilestone = new Map<string, Feature[]>();
  features.forEach((f) => {
    const key = f.milestone || '__none__';
    if (!byMilestone.has(key)) byMilestone.set(key, []);
    byMilestone.get(key)!.push(f);
  });

  const orderedMilestones: string[] = [...milestones.map((m) => m.id), '__none__'];

  orderedMilestones.forEach((msId) => {
    const group = byMilestone.get(msId);
    if (!group || group.length === 0) return;
    const ms = milestoneMap.get(msId);
    if (ms) {
      lines.push(`## Milestone: ${ms.name}${ms.dueDate ? ` (due ${new Date(ms.dueDate).toLocaleDateString()})` : ''}`);
      if (ms.description) lines.push(`> ${ms.description}`);
    } else {
      lines.push('## No Milestone');
    }
    lines.push('');

    group.forEach((f) => {
      const status = f.done ? '✅ Done' : f.inProgress ? '🔆 In Progress' : '⬜ Todo';
      lines.push(`### ${f.title}`);
      lines.push('');
      lines.push('| Field | Value |');
      lines.push('|-------|-------|');
      lines.push(`| Status | ${status} |`);
      lines.push(`| Priority | ${PRIORITY_LABEL[f.priority]} |`);
      if (f.estimate) lines.push(`| Estimate | ${f.estimate === '?' ? '?' : `${f.estimate} pts`} |`);
      if (f.value) lines.push(`| Value | ${f.value === '?' ? '?' : `${f.value} pts`} |`);
      if (f.dueDate) lines.push(`| Due | ${new Date(f.dueDate).toLocaleDateString()} |`);
      if (f.startDate) lines.push(`| Start | ${new Date(f.startDate).toLocaleDateString()} |`);
      if (f.assignee) lines.push(`| Assignee | @${f.assignee} |`);
      if ((f.tags ?? []).length > 0) lines.push(`| Tags | ${f.tags.map((t) => `\`${t}\``).join(', ')} |`);
      if (f.url) lines.push(`| Link | [${f.url}](${f.url}) |`);
      lines.push('');
      if (f.description) {
        lines.push(f.description);
        lines.push('');
      }
      const blockers = (f.blockedBy ?? []).map((bid) => featureMap.get(bid)?.title).filter(Boolean);
      if (blockers.length > 0) {
        lines.push(`**Blocked by:** ${blockers.map((t) => `_${t}_`).join(', ')}`);
        lines.push('');
      }
      if (f.notes?.trim()) {
        lines.push('**Acceptance Criteria / Notes:**');
        lines.push('');
        f.notes.trim().split('\n').forEach((l) => lines.push(l));
        lines.push('');
      }
      lines.push('---');
      lines.push('');
    });
  });

  const md = lines.join('\n');
  const mdBlob = new Blob([md], { type: 'text/markdown' });
  const mdUrl = URL.createObjectURL(mdBlob);
  const a2 = document.createElement('a');
  a2.href = mdUrl;
  a2.download = `${slug}-github-issues.md`;
  a2.click();
  URL.revokeObjectURL(mdUrl);
}

// ---------------------------------------------------------------------------
// Changelog export — grouped by milestone, done features only
// ---------------------------------------------------------------------------
export function exportChangelog(): void {
  const ps = useProjectStore.getState();
  const { features, milestones, meta } = ps;
  const projectName = meta.name || 'Untitled Project';
  const slug = projectName.replace(/\s+/g, '-').toLowerCase();

  const done = features.filter((f) => f.done);
  if (done.length === 0) return;

  const lines: string[] = [];
  lines.push(`# Changelog — ${projectName}`);
  lines.push('');
  lines.push(`_Generated ${new Date().toLocaleDateString()}_`);
  lines.push('');

  // Group by milestone, then "Backlog" bucket for features without milestone
  const byMilestone = new Map<string, Feature[]>();
  const noMilestone: Feature[] = [];

  done.forEach((f) => {
    if (f.milestone) {
      if (!byMilestone.has(f.milestone)) byMilestone.set(f.milestone, []);
      byMilestone.get(f.milestone)!.push(f);
    } else {
      noMilestone.push(f);
    }
  });

  // Sort milestones by their order in the milestones array
  const orderedMilestones = milestones
    .filter((m) => byMilestone.has(m.id) || byMilestone.has(m.name))
    .map((m) => {
      const features = byMilestone.get(m.id) ?? byMilestone.get(m.name) ?? [];
      return { label: m.name, features, dueDate: m.dueDate };
    });

  // Also catch any milestone string that didn't resolve to a milestone object
  byMilestone.forEach((feats, key) => {
    const found = milestones.some((m) => m.id === key || m.name === key);
    if (!found) {
      orderedMilestones.push({ label: key, features: feats, dueDate: undefined });
    }
  });

  const writeGroup = (label: string, feats: Feature[], dueDate?: string) => {
    lines.push(`## ${label}${dueDate ? ` _(${dueDate})_` : ''}`);
    lines.push('');
    // Group by kind within milestone
    const byKind = new Map<string, Feature[]>();
    feats.forEach((f) => {
      const k = f.kind ?? 'feature';
      if (!byKind.has(k)) byKind.set(k, []);
      byKind.get(k)!.push(f);
    });
    const kindOrder = ['feature', 'improvement', 'bug', 'chore'];
    const kindEmoji: Record<string, string> = { feature: '✨', improvement: '⚡', bug: '🐛', chore: '🔧' };
    kindOrder.forEach((k) => {
      const kFeats = byKind.get(k);
      if (!kFeats?.length) return;
      lines.push(`### ${kindEmoji[k] ?? '·'} ${k.charAt(0).toUpperCase() + k.slice(1)}s`);
      lines.push('');
      kFeats.forEach((f) => {
        const tags = f.tags?.length ? ` \`${f.tags.join('` `')}\`` : '';
        const assignee = f.assignee ? ` _(${f.assignee})_` : '';
        const pts = f.estimate && f.estimate !== '?' ? ` [${f.estimate}pt]` : '';
        const completedAt = f.completedAt
          ? ` — _done ${new Date(f.completedAt).toLocaleDateString()}_`
          : '';
        lines.push(`- **${f.title}**${pts}${assignee}${tags}${completedAt}`);
        if (f.description?.trim()) {
          lines.push(`  ${f.description.trim()}`);
        }
        if (f.checklist?.length) {
          const doneCount = f.checklist.filter((c) => c.done).length;
          lines.push(`  ✅ ${doneCount}/${f.checklist.length} subtasks`);
        }
      });
      lines.push('');
    });
    // Any kinds not in kindOrder
    byKind.forEach((kFeats, k) => {
      if (kindOrder.includes(k)) return;
      lines.push(`### · ${k}`);
      lines.push('');
      kFeats.forEach((f) => {
        lines.push(`- **${f.title}**`);
      });
      lines.push('');
    });
  };

  orderedMilestones.forEach(({ label, features: feats, dueDate }) => {
    writeGroup(label, feats, dueDate);
  });

  if (noMilestone.length > 0) {
    writeGroup('Unplanned', noMilestone);
  }

  // Footer stats
  lines.push('---');
  lines.push('');
  const totalPts = done.reduce((s, f) => {
    const n = parseInt(f.estimate ?? '', 10);
    return s + (isNaN(n) ? 0 : n);
  }, 0);
  lines.push(`**Total:** ${done.length} features shipped · ${totalPts} story points`);

  const md = lines.join('\n');
  const blob = new Blob([md], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${slug}-changelog.md`;
  a.click();
  URL.revokeObjectURL(url);
}
