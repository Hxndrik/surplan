export interface BackupData {
  version: number;
  exportedAt: string;
  projectName: string;
  entities: ReturnType<typeof useEntityStore.getState>['entities'];
  meta: ReturnType<typeof useProjectStore.getState>['meta'];
  features: ReturnType<typeof useProjectStore.getState>['features'];
  milestones: ReturnType<typeof useProjectStore.getState>['milestones'];
  scope: ReturnType<typeof useProjectStore.getState>['scope'];
  endpoints: ReturnType<typeof useProjectStore.getState>['endpoints'];
}

export function backupProject(): void {
  const es = useEntityStore.getState();
  const ps = useProjectStore.getState();

  const data: BackupData = {
    version: 1,
    exportedAt: new Date().toISOString(),
    projectName: ps.meta.name || 'Untitled Project',
    entities: es.entities,
    meta: ps.meta,
    features: ps.features,
    milestones: ps.milestones,
    scope: ps.scope,
    endpoints: ps.endpoints,
  };

  const json = JSON.stringify(data, null, 2);
  const blob = new Blob([json], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${(ps.meta.name || 'surplan-project').replace(/\s+/g, '-').toLowerCase()}-backup.json`;
  a.click();
  URL.revokeObjectURL(url);
}

export function restoreProject(file: File): Promise<{ success: boolean; message: string }> {
  return new Promise((resolve) => {
    const reader = new FileReader();
    reader.onload = (e) => {
      try {
        const data = JSON.parse(e.target?.result as string) as BackupData;

        if (!data.version || !data.entities || !data.meta) {
          resolve({ success: false, message: 'Invalid backup file format' });
          return;
        }

        useHistoryStore.setState({ isReverting: true, past: [], future: [] });

        useEntityStore.setState({ entities: data.entities ?? [] });
        useProjectStore.setState({
          meta: data.meta,
          features: data.features ?? [],
          milestones: data.milestones ?? [],
          scope: data.scope ?? [],
          endpoints: data.endpoints ?? [],
        });

        Promise.resolve().then(() =>
          useHistoryStore.setState({ isReverting: false })
        );

        resolve({ success: true, message: `Restored "${data.meta.name || 'project'}" from backup` });
      } catch {
        resolve({ success: false, message: 'Failed to parse backup file' });
      }
    };
    reader.readAsText(file);
  });
}

function entityToMarkdownTable(entity: Entity): string {
  const rows = entity.columns.map((c) => {
    const flags = [
      c.primaryKey ? 'PK' : '',
      c.nullable ? 'NULL' : 'NOT NULL',
      c.unique ? 'UNIQUE' : '',
      c.indexed && !c.primaryKey ? 'INDEX' : '',
      c.defaultValue ? `DEFAULT ${c.defaultValue}` : '',
      c.references ? `FK → ${c.references.entityName}.${c.references.columnName}` : '',
      c.check?.trim() ? `CHECK (${c.check.trim()})` : '',
    ].filter(Boolean).join(', ');
    return `| ${c.name} | ${c.dataType} | ${flags} | ${c.note || ''} |`;
  });
  return [
    `### ${entity.name}`,
    entity.description ? `\n*${entity.description}*\n` : '',
    '',
    '| Column | Type | Constraints | Note |',
    '|--------|------|-------------|------|',
    ...rows,
  ].join('\n');
}

export function exportProjectMarkdown(): void {
  const es = useEntityStore.getState();
  const ps = useProjectStore.getState();
  const { meta, features, milestones, scope, endpoints } = ps;
  const { entities } = es;

  const lines: string[] = [];

  // Header
  lines.push(`# ${meta.name || 'Untitled Project'}`);
  lines.push('');
  if (meta.description) {
    lines.push(meta.description);
    lines.push('');
  }
  lines.push(`> *Generated by surplan · ${new Date().toLocaleDateString()}*`);
  lines.push('');

  // Tech Stack
  if (meta.techStackNotes) {
    lines.push('## Tech Stack');
    lines.push('');
    lines.push(meta.techStackNotes);
    lines.push('');
  }

  // Scope
  const inScope = scope.filter((s) => s.inScope);
  const outScope = scope.filter((s) => !s.inScope);
  if (scope.length > 0) {
    lines.push('## Scope');
    lines.push('');
    if (inScope.length > 0) {
      lines.push('### In Scope');
      inScope.forEach((s) => lines.push(`- ${s.text}`));
      lines.push('');
    }
    if (outScope.length > 0) {
      lines.push('### Out of Scope');
      outScope.forEach((s) => lines.push(`- ${s.text}`));
      lines.push('');
    }
  }

  // Features
  if (features.length > 0) {
    lines.push('## Features');
    lines.push('');

    const doneTotal = features.filter((f) => f.done).length;
    lines.push(`*${doneTotal}/${features.length} complete*`);
    lines.push('');

    // Group by milestone
    const groups = [
      ...milestones.map((m) => ({
        label: m.name,
        items: features.filter((f) => f.milestone === m.id),
      })),
      {
        label: 'Backlog',
        items: features.filter((f) => !f.milestone),
      },
    ].filter((g) => g.items.length > 0);

    for (const group of groups) {
      const done = group.items.filter((f) => f.done).length;
      lines.push(`### ${group.label} (${done}/${group.items.length})`);
      lines.push('');
      for (const f of group.items) {
        const check = f.done ? '[x]' : f.inProgress ? '[-]' : '[ ]';
        const priority = f.priority !== 'medium' ? ` *(${f.priority})*` : '';
        const assigneeMd = f.assignee ? ` @${f.assignee}` : '';
        const dueMd = f.dueDate ? ` 📅 ${f.dueDate}` : '';
        const urlMd = f.url ? ` [🔗](${f.url})` : '';
        lines.push(`- ${check} **${f.title}**${priority}${assigneeMd}${dueMd}${urlMd}`);
        if (f.description) lines.push(`  > ${f.description}`);
        if (f.notes) lines.push(`  *Notes: ${f.notes.replace(/\n/g, ' ')}*`);
        if (f.checklist?.length) {
          f.checklist.forEach((c) => lines.push(`  - [${c.done ? 'x' : ' '}] ${c.text}`));
        }
      }
      lines.push('');
    }
  }

  // API Endpoints
  if (endpoints.length > 0) {
    lines.push('## API Endpoints');
    lines.push('');

    // Group by tag
    const tags = Array.from(new Set(endpoints.map((e) => e.tag || 'General')));
    for (const tag of tags) {
      const tagEps = endpoints.filter((e) => (e.tag || 'General') === tag);
      lines.push(`### ${tag}`);
      lines.push('');
      for (const ep of tagEps) {
        let line = `- \`${ep.method}\` \`${ep.path}\`${ep.description ? ` — ${ep.description}` : ''}`;
        if (ep.queryParams?.trim()) line += ` *(query: ${ep.queryParams})*`;
        if (ep.statusCodes?.trim()) line += ` → ${ep.statusCodes}`;
        lines.push(line);
        if (ep.notes?.trim()) lines.push(`  > ${ep.notes}`);
      }
      lines.push('');
    }
  }

  // Data Model
  if (entities.length > 0) {
    lines.push('## Data Model');
    lines.push('');
    for (const entity of entities) {
      lines.push(entityToMarkdownTable(entity));
      lines.push('');
    }
  }

  const content = lines.join('\n');
  const blob = new Blob([content], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${(meta.name || 'surplan-project').replace(/\s+/g, '-').toLowerCase()}.md`;
  a.click();
  URL.revokeObjectURL(url);
}

